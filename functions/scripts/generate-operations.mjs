// Emits src/api/generated/operations.gen.ts: every operation in openapi.yaml
// with its method, Hono path and auth requirement. The router registers
// routes from this list, so the Worker can't drift from the contract
// (ADR-0015). Run through `npm run generate:api`.
import { readFileSync, writeFileSync } from "node:fs";
import yaml from "js-yaml";

const METHODS = ["get", "put", "post", "delete", "patch"];
const spec = yaml.load(readFileSync("openapi.yaml", "utf8"));
const globalAuth = (spec.security ?? []).length > 0;

const operations = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of METHODS) {
    const op = item[method];
    if (!op) continue;
    operations.push({
      operationId: op.operationId,
      method,
      path,
      honoPath: path.replace(/\{([^}]+)\}/g, ":$1"),
      auth: op.security ? op.security.length > 0 : globalAuth,
    });
  }
}
operations.sort((a, b) => a.operationId.localeCompare(b.operationId));

const body = `// Generated by scripts/generate-operations.mjs from openapi.yaml. Do not edit.

export const operations = ${JSON.stringify(operations, null, 2)} as const;

export type OperationId = (typeof operations)[number]["operationId"];
`;
writeFileSync("src/api/generated/operations.gen.ts", body);
console.log(`operations.gen.ts: ${operations.length} operations`);
